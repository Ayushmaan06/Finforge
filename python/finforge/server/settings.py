"""Server settings, from environment variables (FINFORGE_*)."""

import os
from dataclasses import dataclass, field
from pathlib import Path


def _env(name: str, default: str) -> str:
    return os.environ.get(f"FINFORGE_{name}", default)


@dataclass(frozen=True)
class Settings:
    # SQLAlchemy URL, e.g. postgresql+psycopg://finforge:finforge@localhost:5432/finforge
    database_url: str = field(
        default_factory=lambda: _env(
            "DATABASE_URL", "postgresql+psycopg://finforge:finforge@localhost:5432/finforge"
        )
    )
    # Where uploads, datasets and run directories live. Paths inside are generated by the server.
    storage_dir: Path = field(default_factory=lambda: Path(_env("STORAGE_DIR", "var")).resolve())
    max_upload_bytes: int = field(
        default_factory=lambda: int(_env("MAX_UPLOAD_BYTES", str(512 << 20)))
    )
    lease_seconds: float = field(default_factory=lambda: float(_env("LEASE_SECONDS", "30")))
    heartbeat_seconds: float = field(default_factory=lambda: float(_env("HEARTBEAT_SECONDS", "5")))
    max_attempts: int = field(default_factory=lambda: int(_env("MAX_ATTEMPTS", "2")))
    poll_seconds: float = field(default_factory=lambda: float(_env("POLL_SECONDS", "1")))
    progress_every: int = field(default_factory=lambda: int(_env("PROGRESS_EVERY", "8192")))

    @property
    def uploads_dir(self) -> Path:
        return self.storage_dir / "uploads"

    @property
    def datasets_dir(self) -> Path:
        return self.storage_dir / "datasets"

    @property
    def runs_dir(self) -> Path:
        return self.storage_dir / "runs"

    def ensure_dirs(self) -> None:
        for d in (self.uploads_dir, self.datasets_dir, self.runs_dir):
            d.mkdir(parents=True, exist_ok=True)
