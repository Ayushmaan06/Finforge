"""Relational model (PLAN Phase 7 task 2) and database helpers. SQLAlchemy 2, PostgreSQL.

Bulk data (market data, run artefacts) stays in Parquet on disk (D7); the database holds metadata,
statuses, metric summaries and the job queue.
"""

from datetime import datetime
from pathlib import Path
from typing import Any

from sqlalchemy import (
    JSON,
    BigInteger,
    Boolean,
    DateTime,
    Float,
    ForeignKey,
    Integer,
    String,
    Text,
    create_engine,
    func,
)
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.engine import Engine
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column, sessionmaker

Json = JSON().with_variant(JSONB(), "postgresql")

RUN_STATUSES = ("queued", "running", "completed", "failed", "cancelled")
JOB_STATUSES = ("queued", "running", "done", "failed", "cancelled")


class Base(DeclarativeBase):
    pass


def _now() -> Any:
    return mapped_column(DateTime(timezone=True), server_default=func.now(), nullable=False)


class Upload(Base):
    __tablename__ = "uploads"
    id: Mapped[str] = mapped_column(String(36), primary_key=True)
    original_name: Mapped[str] = mapped_column(String(120))  # sanitised, informational only
    stored_path: Mapped[str] = mapped_column(Text)  # generated by the server
    size: Mapped[int] = mapped_column(BigInteger)
    sha256: Mapped[str] = mapped_column(String(64))
    content_type: Mapped[str] = mapped_column(String(16))  # sniffed: csv | zip | parquet | json
    created_at: Mapped[datetime] = _now()


class Dataset(Base):
    __tablename__ = "datasets"
    id: Mapped[str] = mapped_column(String(64), primary_key=True)  # manifest content hash (D6)
    name: Mapped[str] = mapped_column(String(120))
    path: Mapped[str] = mapped_column(Text)
    schema_version: Mapped[int] = mapped_column(Integer)
    time_first_ns: Mapped[int | None] = mapped_column(BigInteger)
    time_last_emit_ns: Mapped[int | None] = mapped_column(BigInteger)
    files: Mapped[Any] = mapped_column(Json)
    validation: Mapped[Any] = mapped_column(Json)
    manifest: Mapped[Any] = mapped_column(Json)
    created_at: Mapped[datetime] = _now()


class Instrument(Base):
    __tablename__ = "instruments"
    dataset_id: Mapped[str] = mapped_column(
        ForeignKey("datasets.id", ondelete="CASCADE"), primary_key=True
    )
    instrument_id: Mapped[int] = mapped_column(Integer, primary_key=True)
    symbol: Mapped[str] = mapped_column(String(64))
    asset_class: Mapped[str] = mapped_column(String(32))
    quote_currency: Mapped[str] = mapped_column(String(16))
    tick_size: Mapped[str] = mapped_column(String(32))
    lot_size: Mapped[str] = mapped_column(String(32))
    min_qty: Mapped[int] = mapped_column(BigInteger)
    contract_multiplier: Mapped[int] = mapped_column(BigInteger)


class StrategyRow(Base):
    __tablename__ = "strategies"
    name: Mapped[str] = mapped_column(String(64), primary_key=True)
    description: Mapped[str] = mapped_column(Text)
    params_schema: Mapped[Any] = mapped_column(Json)
    defaults: Mapped[Any] = mapped_column(Json)
    source_sha256: Mapped[str] = mapped_column(String(64))
    updated_at: Mapped[datetime] = _now()


class Run(Base):
    __tablename__ = "runs"
    id: Mapped[str] = mapped_column(String(36), primary_key=True)
    status: Mapped[str] = mapped_column(String(16), index=True)
    dataset_id: Mapped[str] = mapped_column(ForeignKey("datasets.id"))
    strategy: Mapped[str] = mapped_column(ForeignKey("strategies.name"))
    config: Mapped[Any] = mapped_column(Json)
    strategy_hash: Mapped[str | None] = mapped_column(String(64))
    journal_hash: Mapped[str | None] = mapped_column(String(64))
    engine_version: Mapped[str | None] = mapped_column(String(128))
    created_at: Mapped[datetime] = _now()
    started_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    finished_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    wall_seconds: Mapped[float | None] = mapped_column(Float)
    error: Mapped[Any | None] = mapped_column(Json)
    artefact_dir: Mapped[str | None] = mapped_column(Text)
    partial: Mapped[bool | None] = mapped_column(Boolean)
    reconciles: Mapped[bool | None] = mapped_column(Boolean)


class RunMetrics(Base):
    __tablename__ = "run_metrics"
    run_id: Mapped[str] = mapped_column(ForeignKey("runs.id", ondelete="CASCADE"), primary_key=True)
    total_return: Mapped[float | None] = mapped_column(Float)
    cagr: Mapped[float | None] = mapped_column(Float)
    volatility: Mapped[float | None] = mapped_column(Float)
    sharpe: Mapped[float | None] = mapped_column(Float)
    sortino: Mapped[float | None] = mapped_column(Float)
    max_drawdown: Mapped[float | None] = mapped_column(Float)
    var: Mapped[float | None] = mapped_column(Float)
    cvar: Mapped[float | None] = mapped_column(Float)
    trades: Mapped[int | None] = mapped_column(Integer)
    win_rate: Mapped[float | None] = mapped_column(Float)
    profit_factor: Mapped[float | None] = mapped_column(Float)
    fees: Mapped[float | None] = mapped_column(Float)
    benchmark_return: Mapped[float | None] = mapped_column(Float)


class Job(Base):
    __tablename__ = "jobs"
    id: Mapped[int] = mapped_column(BigInteger, primary_key=True, autoincrement=True)
    run_id: Mapped[str] = mapped_column(ForeignKey("runs.id", ondelete="CASCADE"), unique=True)
    status: Mapped[str] = mapped_column(String(16), index=True)
    attempts: Mapped[int] = mapped_column(Integer, default=0)
    max_attempts: Mapped[int] = mapped_column(Integer)
    lease_until: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    worker_id: Mapped[str | None] = mapped_column(String(64))
    progress: Mapped[float] = mapped_column(Float, default=0.0)
    events_processed: Mapped[int] = mapped_column(BigInteger, default=0)
    sim_time_ns: Mapped[int | None] = mapped_column(BigInteger)
    cancel_requested: Mapped[bool] = mapped_column(Boolean, default=False)
    last_error: Mapped[str | None] = mapped_column(Text)
    created_at: Mapped[datetime] = _now()
    updated_at: Mapped[datetime] = _now()


def make_engine(url: str) -> Engine:
    return create_engine(url, pool_pre_ping=True, future=True)


def session_factory(engine: Engine) -> sessionmaker:
    return sessionmaker(engine, expire_on_commit=False)


def migrate(url: str) -> None:
    """Apply every Alembic migration (python/finforge/server/migrations)."""
    from alembic import command
    from alembic.config import Config

    cfg = Config()
    cfg.set_main_option("script_location", str(Path(__file__).parent / "migrations"))
    cfg.set_main_option("sqlalchemy.url", url.replace("%", "%%"))
    command.upgrade(cfg, "head")
